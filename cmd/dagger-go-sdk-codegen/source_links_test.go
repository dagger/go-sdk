func TestNormalizeGeneratedSourceLinksEnumCaseAliases(t *testing.T) {
	anchor, err := workspaceSourceLinkAnchor(capturedRepo, capturedPin)
	require.NoError(t, err)
	firstLink := anchor + "src/main.go#L10"
	secondLink := anchor + "src/main.go#L20"
	first := sourceLinkDirective("fixture", "src/main.go", 10, 2, firstLink)
	second := sourceLinkDirective("fixture", "src/main.go", 20, 2, secondLink)
	value := `"one"`
	for _, directives := range []*introspection.Directives{&first, &second} {
		*directives = append(*directives, &introspection.Directive{Name: "enumValue", Args: []*introspection.DirectiveArg{{Name: "value", Value: &value}}})
	}
	schema := &introspection.Schema{Types: introspection.Types{{
		Kind: introspection.TypeKindEnum, Name: "Choice",
		EnumValues: []introspection.EnumValue{{Name: "FIRST", Directives: first}, {Name: "first", Directives: second}},
	}}}
	data := "// Code generated by dagger. DO NOT EDIT.\npackage fixture\n" +
		"const ChoiceFirst Choice = \"one\" // fixture (" + firstLink + ")\n"
	result, err := normalizeGeneratedSourceLinks("fixture.go", []byte(data), newSourceLinkCatalog(schema, "v1.0.0"), anchor, "../../..")
	require.NoError(t, err)
	require.Equal(t, "// Code generated by dagger. DO NOT EDIT.\npackage fixture\nconst ChoiceFirst Choice = \"one\" // fixture (../../../src/main.go:10:2)\n", string(result))
}

func TestNormalizeSourceLinksCommandScope(t *testing.T) {
	output := t.TempDir()
	generated := filepath.Join(output, "src", "internal", "dagger", "go.gen.go")
	require.NoError(t, os.MkdirAll(filepath.Dir(generated), 0o755))
	git, err := os.ReadFile("testdata/source-links/git.go.txt")
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(generated, git, 0o640))
	require.NoError(t, runNormalizeSourceLinks([]string{
		"--introspection-json-path", "testdata/source-links/schema.json",
		"--output", output, "--scope", ".dagger/modules/cli",
		"--workspace-repo-url", capturedRepo, "--workspace-pin", capturedPin,
	}))
	result, err := os.ReadFile(generated)
	require.NoError(t, err)
	require.Contains(t, string(result), "../../../../../../.dagger/modules/go/main.go:643:1)")
	info, err := os.Stat(generated)
	require.NoError(t, err)
	require.Equal(t, os.FileMode(0o640), info.Mode().Perm())
}
