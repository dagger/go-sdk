// loadDependencyAliasModule loads a module whose global client aliases the
// types of a dependency client, as unified generation writes them.
func loadDependencyAliasModule(t *testing.T, mainGo string) (*packages.Package, *token.FileSet) {
	t.Helper()
	dir := t.TempDir()
	write := func(path, contents string) {
		require.NoError(t, os.MkdirAll(filepath.Dir(filepath.Join(dir, path)), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join(dir, path), []byte(contents), 0o644))
	}
	write("go.mod", "module example.com/m\n\ngo 1.26\n")
	write("internal/dagger/clients/app/app.gen.go", "// Code generated by dagger. DO NOT EDIT.\n\npackage app\n\ntype App struct{ id string }\n\n"+
		"type AppMode string\n\nconst AppModeFast AppMode = \"FAST\"\n\ntype Pet interface{ Name() string }\n\ntype PetClient struct{ id string }\n")
	write("internal/dagger/dagger.gen.go", "// Code generated by dagger. DO NOT EDIT.\n\npackage dagger\n\nimport dep0 \"example.com/m/internal/dagger/clients/app\"\n\n"+
		"type App = dep0.App\ntype AppMode = dep0.AppMode\ntype Pet = dep0.Pet\n")
	write("main.go", mainGo)
	fset := token.NewFileSet()
	pkgs, err := packages.Load(&packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedImports | packages.NeedDeps | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedModule,
		Dir:  dir,
		Fset: fset,
	}, ".")
	require.NoError(t, err)
	require.Len(t, pkgs, 1)
	require.Empty(t, pkgs[0].Errors)
	return pkgs[0], fset
}

// A private field holding a dependency client's type is spelled through the
// global client's alias in the module package, as the embedded bindings did,
// or through the client package when the author imports it.
func TestDependencyFieldTypeKeepsAuthorSpelling(t *testing.T) {
	pkg, fset := loadDependencyAliasModule(t, "package main\n\nimport (\n\tmodule \"example.com/m/internal/dagger\"\n\tclient \"example.com/m/internal/dagger/clients/app\"\n)\n\n"+
		"type M struct {\n\tGlobal *module.App\n\tMode   module.AppMode\n\tPet    module.Pet\n\tDirect *client.App\n\tPets   []module.Pet\n}\n\nfunc main() {}\n")
	ps := &parseState{pkg: pkg, fset: fset, moduleName: "m"}
	fields := pkg.Types.Scope().Lookup("M").Type().Underlying().(*types.Struct)
	for i, want := range []string{"*dagger.App", "dagger.AppMode", "*dagger.PetClient", "*client.App", "[]*dagger.PetClient"} {
		parsed, err := ps.parseGoTypeReference(fields.Field(i).Type(), nil, false)
		require.NoError(t, err)
		code, err := (&parsedObjectType{}).concreteFieldTypeCode(parsed)
		require.NoError(t, err)
		require.Equal(t, want, strings.TrimSpace(fmt.Sprintf("%#v", code)))
	}
}

func TestDependencyTypeInModuleAPIIsRefused(t *testing.T) {
	pkg, fset := loadDependencyAliasModule(t, "package main\n\nimport module \"example.com/m/internal/dagger\"\n\n"+
		"type M struct{}\n\nfunc (m *M) Describe(app *module.App) string { return \"\" }\n\nfunc main() {}\n")
	funcs := goTemplateFuncs{
		cfg:        generator.Config{ModuleConfig: &generator.ModuleGeneratorConfig{ModuleName: "m"}},
		namer:      goNamer{names: styled},
		modulePkg:  pkg,
		moduleFset: fset,
	}
	noop := func(*parseState, *types.Named, *types.TypeName, *parsedObjectType, *types.Struct) error { return nil }
	err := funcs.visitTypes(false, &visitorFuncs{
		RootVisitor:   func(string) error { return nil },
		StructVisitor: noop,
		IfaceVisitor:  func(*parseState, *types.Named, *types.TypeName, *parsedIfaceType, *types.Interface) error { return nil },
		EnumVisitor:   func(*parseState, *types.Named, *types.TypeName, *parsedEnumType, *types.Basic) error { return nil },
	})
	require.EqualError(t, err, "the module's API uses App, a type of a dependency: a module with a Dang entrypoint can hold it only in private fields and function bodies")
}
