func TestGenerateRefusesParentGoModuleBeforeWriting(t *testing.T) {
	parent := t.TempDir()
	writeTestFile(t, filepath.Join(parent, "go.mod"), "module example.com/project\n\ngo 1.26\n")
	root := filepath.Join(parent, "module")
	if err := os.MkdirAll(root, 0755); err != nil {
		t.Fatal(err)
	}
	writeTestFile(t, filepath.Join(root, "main.go"), "package main\n\ntype HelloWorld struct{}\n")
	err := Generate(t.Context(), GenerateConfig{ModuleRoot: root, ModuleName: "hello-world"})
	if err == nil || !strings.Contains(err.Error(), "parent go.mod") {
		t.Fatalf("Generate() error = %v", err)
	}
	entries, err := os.ReadDir(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 1 || entries[0].Name() != "main.go" {
		t.Errorf("a refused module changed: %v", entries)
	}
}

func TestGenerateRefusesToOverwriteUserFiles(t *testing.T) {
	for _, rel := range []string{
		"cmd/hello-world-dispatch/main.go",
		"internal/dagger/entrypoint/main.dang",
		"dagger.gen.go",
	} {
		t.Run(rel, func(t *testing.T) {
			root := t.TempDir()
			writeTestFile(t, filepath.Join(root, "main.go"), "package hello_world\n\ntype HelloWorld struct{}\n")
			userFile := filepath.Join(root, filepath.FromSlash(rel))
			if err := os.MkdirAll(filepath.Dir(userFile), 0o755); err != nil {
				t.Fatal(err)
			}
			writeTestFile(t, userFile, "user code\n")

			err := Generate(t.Context(), GenerateConfig{ModuleRoot: root, ModuleName: "hello-world"})
			if err == nil || !strings.Contains(err.Error(), rel+" exists and is not generated code") {
				t.Fatalf("Generate() error = %v, want a collision error for %s", err, rel)
			}
			data, err := os.ReadFile(userFile)
			if err != nil {
				t.Fatal(err)
			}
			if string(data) != "user code\n" {
				t.Errorf("%s was overwritten: %q", rel, data)
			}
			if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
				t.Error("go.mod was created before the collision was reported")
			}
		})
	}
}

func TestCheckGeneratedPathAcceptsGeneratedFiles(t *testing.T) {
	root := t.TempDir()
	for name, contents := range map[string]string{
		"main.go":   "// Code generated by dagger. DO NOT EDIT.\n\npackage main\n",
		"main.dang": "# Code generated by dagger. Do not edit.\n\ntype Entrypoint {}\n",
	} {
		path := filepath.Join(root, name)
		writeTestFile(t, path, contents)
		if err := checkGeneratedPath(root, path); err != nil {
			t.Errorf("checkGeneratedPath(%s) = %v", name, err)
		}
	}
	if err := checkGeneratedPath(root, filepath.Join(root, "missing.go")); err != nil {
		t.Errorf("checkGeneratedPath(missing) = %v", err)
	}
}

