func TestEnsureGoModuleUsesEnclosingModule(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, filepath.Join(root, "go.mod"), "module example.com/app\n\ngo 1.25\n")
	moduleRoot := filepath.Join(root, "mods", "hello")
	if err := os.MkdirAll(moduleRoot, 0o755); err != nil {
		t.Fatal(err)
	}

	packageImport, goModPath, err := ensureGoModule(moduleRoot, "hello")
	if err != nil {
		t.Fatal(err)
	}
	if packageImport != "example.com/app/mods/hello" {
		t.Errorf("package import = %q, want example.com/app/mods/hello", packageImport)
	}
	if goModPath != filepath.Join(root, "go.mod") {
		t.Errorf("go.mod path = %q, want the enclosing go.mod", goModPath)
	}
	if _, err := os.Stat(filepath.Join(moduleRoot, "go.mod")); err == nil {
		t.Error("a nested go.mod was created")
	}
}

func TestPinDaggerKeepsReplaceAndNewerVersion(t *testing.T) {
	for name, goMod := range map[string]string{
		"replace":        "module example.com/app\n\ngo 1.25\n\nreplace dagger.io/dagger => ../sdk\n",
		"newer required": "module example.com/app\n\ngo 1.25\n\nrequire dagger.io/dagger v1.0.0-beta.20\n",
	} {
		t.Run(name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "go.mod")
			writeTestFile(t, path, goMod)

			if err := pinDagger(path, "v1.0.0-beta.14"); err != nil {
				t.Fatal(err)
			}
			data, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			if string(data) != goMod {
				t.Errorf("go.mod changed:\n%s", data)
			}
		})
	}
}

func TestRemoveStaleBindingsReportsRemovedFiles(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "internal", "dagger")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	generated := "// Code generated by dagger. DO NOT EDIT.\n\npackage dagger\n"
	writeTestFile(t, filepath.Join(dir, "dagger.gen.go"), generated)
	writeTestFile(t, filepath.Join(dir, "kept.gen.go"), generated)
	writeTestFile(t, filepath.Join(dir, "stale.gen.go"), generated)
	writeTestFile(t, filepath.Join(dir, "user.gen.go"), "package dagger\n")
	overlay := fstest.MapFS{"internal/dagger/kept.gen.go": {Data: []byte(generated)}}

	removed, err := removeStaleBindings(root, overlay)
	if err != nil {
		t.Fatal(err)
	}
	if len(removed) != 1 || removed[0] != "internal/dagger/stale.gen.go" {
		t.Errorf("removed = %v, want [internal/dagger/stale.gen.go]", removed)
	}
	for name, want := range map[string]bool{"dagger.gen.go": true, "kept.gen.go": true, "stale.gen.go": false, "user.gen.go": true} {
		if _, err := os.Stat(filepath.Join(dir, name)); (err == nil) != want {
			t.Errorf("%s exists = %t, want %t", name, err == nil, want)
		}
	}
}

func writeTestFile(t *testing.T, path, contents string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(contents), 0o644); err != nil {
		t.Fatal(err)
	}
}
