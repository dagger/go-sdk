// collectionBuildSources rewrites a temporary build copy. Author files remain
// untouched, while copied collection values retain the engine's private base.
// The copy holds buildRoot, so the package loads with the files beside root
// that its build reads.
func collectionBuildSources(ctx context.Context, buildRoot, root string) (map[string][]byte, error) {
	paths, err := filepath.Glob(filepath.Join(root, "*.go"))
	if err != nil {
		return nil, err
	}
	needed := false
	for _, path := range paths {
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		if bytes.Contains(data, []byte("+collection")) {
			needed = true
		}
	}
	if !needed {
		return nil, nil
	}
	modulePath, err := filepath.Rel(buildRoot, root)
	if err != nil {
		return nil, fmt.Errorf("resolve module path in build root: %w", err)
	}
	staged, err := os.MkdirTemp("", "go-collection-build-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(staged)
	if err = os.CopyFS(staged, os.DirFS(buildRoot)); err != nil {
		return nil, fmt.Errorf("copy collection build source: %w", err)
	}
	if err = ctx.Err(); err != nil {
		return nil, err
	}
	dir := filepath.Join(staged, modulePath)
	if err = clientgen.PrepareCollectionRuntime(dir); err != nil {
		return nil, err
	}
	result := map[string][]byte{}
	for _, path := range paths {
		name := filepath.Base(path)
		old, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, err
		}
		if !bytes.Equal(old, data) {
			result[name] = data
		}
	}
	return result, nil
}

func writeCollectionBuild(root string, entrypoint []byte, files map[string][]byte) ([]byte, error) {
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	if len(names) == 0 {
		return entrypoint, nil
	}
	// An entrypoint whose dispatch builds for a given platform takes it.
	dispatch := []byte("  let dispatch: File! {")
	if declared := []byte("  let dispatch(platform: Platform!): File! {"); bytes.Contains(entrypoint, declared) {
		dispatch = declared
	}
	// The call runs the binary on the module context. A go build dispatch
	// mounts the context too; a dagger/go one reads it as a workspace.
	mount := []byte(`.withMountedDirectory("/workspace", currentModule.contextDirectory)`)
	workspace := []byte("currentModule.contextDirectory.asWorkspace")
	goBuild := bytes.Count(entrypoint, mount) == 2 && !bytes.Contains(entrypoint, workspace)
	daggerGo := bytes.Count(entrypoint, mount) == 1 && bytes.Count(entrypoint, workspace) == 1
	if bytes.Count(entrypoint, dispatch) != 1 || !(goBuild || daggerGo) {
		return nil, fmt.Errorf("collection build: the entrypoint needs one dispatch, which reads the module context once, and one call that mounts it, to rewrite")
	}
	var overlay strings.Builder
	overlay.WriteString("  let collectionContext: Directory! {\n    currentModule.contextDirectory")
	for _, name := range names {
		if !fs.ValidPath(name) || filepath.Base(name) != name {
			return nil, fmt.Errorf("invalid runtime source path %q", name)
		}
		rel := "internal/dagger/entrypoint/runtime/" + name + ".src"
		if err := checkGeneratedPath(root, filepath.Join(root, rel)); err != nil {
			return nil, err
		}
		data := append([]byte("// Code generated by dagger. DO NOT EDIT.\n"), files[name]...)
		if err := writeFile(filepath.Join(root, rel), data); err != nil {
			return nil, err
		}
		fmt.Fprintf(&overlay, "\n      .withFile(currentModule.sourceSubpath + %s, currentModule.contextDirectory.file(currentModule.sourceSubpath + %s))",
			strconv.Quote("/"+name), strconv.Quote("/"+rel))
	}
	overlay.WriteString("\n  }\n\n")
	overlay.Write(dispatch)
	entrypoint = bytes.Replace(entrypoint, dispatch, []byte(overlay.String()), 1)
	entrypoint = bytes.ReplaceAll(entrypoint, workspace, []byte("collectionContext.asWorkspace"))
	return bytes.ReplaceAll(entrypoint, mount, []byte(`.withMountedDirectory("/workspace", collectionContext)`)), nil
}
